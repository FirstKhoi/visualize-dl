"""The same CNN as train_mnist_cnn.py, trained with PyTorch: for Google Colab or any machine with torch.

    pip install torch torchvision
    python training/mnist_cnn_pytorch.py          # from the repository root

It writes the same three files as the NumPy script, in the same format, so the page and its tests take either:
models/weights/mnist-cnn.js, tests/fixtures/mnist-cnn.json (logits computed in float64, as the page computes) and
training/results.json. Afterwards run `npm test` and `./build-pages.sh`.

Note: the weights in this repository come from train_mnist_cnn.py. This script has not been run in the environment
that produced them (it had no PyTorch), so check its numbers the first time you run it.
"""
import base64
import json
import pathlib

import torch
import torch.nn as nn
import torch.nn.functional as F
from torchvision import datasets, transforms

ROOT = pathlib.Path(__file__).resolve().parent.parent
SEED, EPOCHS, BATCH, LR = 0, 6, 64, 1e-3


class Net(nn.Module):
    """conv 3×3 ×8 → ReLU → max-pool 2 → conv 3×3 ×16 → ReLU → max-pool 2 → linear 400 → 10 (5 258 parameters)."""

    def __init__(self):
        super().__init__()
        self.conv1 = nn.Conv2d(1, 8, 3)
        self.conv2 = nn.Conv2d(8, 16, 3)
        self.fc = nn.Linear(16 * 5 * 5, 10)

    def forward(self, x):
        x = F.max_pool2d(F.relu(self.conv1(x)), 2)
        x = F.max_pool2d(F.relu(self.conv2(x)), 2)
        return self.fc(torch.flatten(x, 1))


def main():
    torch.manual_seed(SEED)
    data = ROOT / 'training' / 'data'
    # pixels to [0, 1] with no normalisation, as the page feeds its drawing; shifts of up to 2 px, as the NumPy script
    train = datasets.MNIST(data, train=True, download=True,
                           transform=transforms.Compose([transforms.RandomAffine(0, translate=(2 / 28, 2 / 28)), transforms.ToTensor()]))
    test = datasets.MNIST(data, train=False, download=True, transform=transforms.ToTensor())
    loader = torch.utils.data.DataLoader(train, batch_size=BATCH, shuffle=True)
    test_x = test.data.float().div(255).unsqueeze(1)  # all 10 000 test images at once: (10000, 1, 28, 28)
    test_y = test.targets

    model = Net()
    opt = torch.optim.Adam(model.parameters(), lr=LR)
    history = []
    for epoch in range(1, EPOCHS + 1):
        model.train()
        losses, hits, seen = 0.0, 0, 0
        for x, y in loader:
            logits = model(x)
            loss = F.cross_entropy(logits, y)
            opt.zero_grad()
            loss.backward()
            opt.step()
            losses += loss.item() * len(y)
            hits += (logits.argmax(1) == y).sum().item()
            seen += len(y)
        model.eval()
        with torch.no_grad():
            out = model(test_x)
            history.append({'epoch': epoch, 'train_loss': losses / seen, 'train_acc': hits / seen,
                            'test_loss': F.cross_entropy(out, test_y).item(), 'test_acc': (out.argmax(1) == test_y).float().mean().item()})
        print(history[-1])

    # the page gets 5 significant digits per weight; measure everything with exactly those, in float64 like the page
    rounded = {k: torch.tensor([float(f'{w:.5g}') for w in v.flatten().tolist()], dtype=torch.float64).reshape(v.shape)
               for k, v in model.state_dict().items()}
    model.double().load_state_dict(rounded)
    with torch.no_grad():
        logits = model(test_x.double())
    test_acc = (logits.argmax(1) == test_y).double().mean().item()
    test_loss = F.cross_entropy(logits, test_y).item()
    right = logits.argmax(1) == test_y
    first = [int(torch.nonzero((test_y == d) & right)[0]) for d in range(10)]  # one correctly classified test image per digit
    images = test.data  # uint8 (10000, 28, 28)
    n_params = sum(v.numel() for v in rounded.values())
    print(f'{n_params} parameters; test accuracy with the exported weights: {test_acc:.4f}')

    weights = {k: {'shape': list(v.shape), 'data': v.flatten().tolist()} for k, v in rounded.items()}
    meta = {'params': n_params, 'test_acc': test_acc, 'test_loss': test_loss, 'epochs': EPOCHS,
            'samples': [{'label': d, 'pixels': base64.b64encode(images[i].numpy().tobytes()).decode()} for d, i in enumerate(first)]}
    (ROOT / 'models' / 'weights' / 'mnist-cnn.js').write_text(
        '// Generated by training/mnist_cnn_pytorch.py: do not edit by hand.\n'
        '// A small CNN trained on MNIST (LeCun, Cortes & Burges, CC BY-SA 3.0); weights in PyTorch state_dict layout,\n'
        '// samples: one MNIST test image per digit (28×28 uint8, base64).\n'
        f'const MNIST_CNN = {json.dumps({"weights": weights, **meta}, separators=(",", ":"))};\n')
    (ROOT / 'tests' / 'fixtures' / 'mnist-cnn.json').write_text(json.dumps({
        'images': [images[i].flatten().tolist() for i in range(5)], 'labels': test_y[:5].tolist(),
        'logits': logits[:5].tolist(), 'test_acc': test_acc}) + '\n')
    (ROOT / 'training' / 'results.json').write_text(json.dumps({'framework': 'pytorch', 'seed': SEED, 'epochs': EPOCHS, 'batch': BATCH,
        'lr': LR, 'augmentation': 'random shift up to 2 px', 'params': n_params, 'history': history,
        'exported_test_acc': test_acc, 'exported_test_loss': test_loss}, indent=2) + '\n')


if __name__ == '__main__':
    main()
